#!/usr/bin/env python3
"""Generates the 拾影 2.1 launcher icon (adaptive vector + legacy PNGs) from one geometry definition.
Design: orange→red gradient rounded square, white rounded play triangle, white down arrow, two fading speed lines
(user's pick: icon-src/icon-r2c3.png). Geometry is in a 368-unit square (the design's rounded square)."""
import math, os, subprocess, sys
ROOT = os.path.dirname(os.path.abspath(__file__)) + '/..'
RES = ROOT + '/app/src/main/res'
ORANGE, RED = '#FF7A1A', '#F0143C'

def rounded_poly(pts, r):
    n = len(pts); d = ''
    for i in range(n):
        p0, p1, p2 = pts[i - 1], pts[i], pts[(i + 1) % n]
        def toward(a, b, dist):
            L = math.hypot(b[0] - a[0], b[1] - a[1]); dist = min(dist, L / 2.2)
            return (a[0] + (b[0] - a[0]) * dist / L, a[1] + (b[1] - a[1]) * dist / L)
        a = toward(p1, p0, r); b = toward(p1, p2, r)
        d += ('M' if i == 0 else 'L') + f'{a[0]:.2f},{a[1]:.2f}Q{p1[0]:.2f},{p1[1]:.2f} {b[0]:.2f},{b[1]:.2f}'
    return d + 'Z'

def rrect(x0, y0, x1, y1, r):
    return (f'M{x0 + r},{y0}L{x1 - r},{y0}A{r},{r} 0 0 1 {x1},{y0 + r}L{x1},{y1 - r}A{r},{r} 0 0 1 {x1 - r},{y1}'
            f'L{x0 + r},{y1}A{r},{r} 0 0 1 {x0},{y1 - r}L{x0},{y0 + r}A{r},{r} 0 0 1 {x0 + r},{y0}Z')

PLAY = rounded_poly([(122, 70), (254, 142), (122, 214)], 18)
ARROW = rounded_poly([(254, 175), (300, 175), (300, 227), (335, 227), (277, 297), (220, 227), (254, 227)], 6)
LINES = [(82, 234.5, 192, 247.5), (57, 262.5, 157, 275.5)]   # x0,y0,x1,y1 (fade in from the left)

# content bbox ≈ x 57..335, y 70..297 → fit into the adaptive safe zone (66 dp circle of a 108 dp canvas)
CX, CY = 196, 183.5
S = 0.68 * 108 / 368
TX, TY = 54 - CX * S, 54 - CY * S

def vec_fg(mono=False):
    lines = ''
    for i, (x0, y0, x1, y1) in enumerate(LINES):
        fill = 'android:fillColor="#FFFFFFFF"' if mono else ''
        grad = '' if mono else f'''
            <aapt:attr name="android:fillColor">
                <gradient android:type="linear" android:startX="{x0}" android:startY="0" android:endX="{x1}" android:endY="0"
                    android:startColor="#00FFFFFF" android:endColor="#F2FFFFFF"/>
            </aapt:attr>'''
        lines += f'''
        <path android:pathData="{rrect(x0, y0, x1, y1, 6.5)}" {fill}>{grad}
        </path>''' if not mono else f'''
        <path android:pathData="{rrect(x0, y0, x1, y1, 6.5)}" {fill}/>'''
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- generated by icon-src/make_icon.py -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <group android:scaleX="{S:.5f}" android:scaleY="{S:.5f}" android:translateX="{TX:.4f}" android:translateY="{TY:.4f}">{lines}
        <path android:pathData="{PLAY}" android:fillColor="#FFFFFFFF"/>
        <path android:pathData="{ARROW}" android:fillColor="#FFFFFFFF"/>
    </group>
</vector>
'''

VEC_BG = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- generated by icon-src/make_icon.py -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="linear" android:startX="0" android:startY="0" android:endX="108" android:endY="108"
                android:startColor="{ORANGE}" android:endColor="{RED}"/>
        </aapt:attr>
    </path>
</vector>
'''

def svg(size, shape):
    """shape: 'squircle' (legacy square icon, rounded corners like the design), 'circle', or 'full' (adaptive preview)."""
    k = size / 108
    clip = {'squircle': f'<rect x="{4*k}" y="{4*k}" width="{100*k}" height="{100*k}" rx="{23*k}"/>',
            'circle': f'<circle cx="{54*k}" cy="{54*k}" r="{50*k}"/>',
            'full': f'<rect width="{size}" height="{size}"/>'}[shape]
    # legacy icons: show the whole design (content scaled to the 100-unit shape instead of the 66-unit safe zone)
    s = (S / 0.68 * 100 / 108) if shape != 'full' else S
    tx, ty = 54 - CX * s, 54 - CY * s
    grads = ''.join(f'<linearGradient id="l{i}" gradientUnits="userSpaceOnUse" x1="{x0}" y1="0" x2="{x1}" y2="0">'
                    f'<stop offset="0" stop-color="#fff" stop-opacity="0"/><stop offset="1" stop-color="#fff" stop-opacity="0.95"/></linearGradient>'
                    for i, (x0, y0, x1, y1) in enumerate(LINES))
    lines = ''.join(f'<path d="{rrect(x0, y0, x1, y1, 6.5)}" fill="url(#l{i})"/>' for i, (x0, y0, x1, y1) in enumerate(LINES))
    return f'''<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="0 0 {size} {size}">
<defs><linearGradient id="bg" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="{ORANGE}"/><stop offset="1" stop-color="{RED}"/></linearGradient>
<clipPath id="c">{clip}</clipPath>{grads}</defs>
<g clip-path="url(#c)"><rect width="{size}" height="{size}" fill="url(#bg)"/>
<g transform="scale({k}) translate({tx:.4f},{ty:.4f}) scale({s:.5f})">{lines}<path d="{PLAY}" fill="#fff"/><path d="{ARROW}" fill="#fff"/></g></g></svg>'''

def render(svg_text, size, out):
    html = f'<html><body style="margin:0;background:transparent">{svg_text}</body></html>'
    tmp = '/tmp/icon-render.html'; open(tmp, 'w').write(html)
    subprocess.run(['/workspace/work/chromium.sh', '--headless=new', '--disable-gpu', '--hide-scrollbars', '--default-background-color=00000000',
                    f'--window-size={size},{size}', f'--screenshot={out}', 'file://' + tmp], check=True, capture_output=True, timeout=60)

if __name__ == '__main__':
    open(RES + '/drawable/ic_fg.xml', 'w').write(vec_fg())
    open(RES + '/drawable/ic_mono.xml', 'w').write(vec_fg(mono=True))
    open(RES + '/drawable/ic_bg.xml', 'w').write(VEC_BG)
    for name in ('ic_launcher', 'ic_launcher_round'):
        open(RES + f'/mipmap-anydpi-v26/{name}.xml', 'w').write('''<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_bg"/>
    <foreground android:drawable="@drawable/ic_fg"/>
    <monochrome android:drawable="@drawable/ic_mono"/>
</adaptive-icon>
''')
    for d, px in {'mdpi': 48, 'hdpi': 72, 'xhdpi': 96, 'xxhdpi': 144, 'xxxhdpi': 192}.items():
        os.makedirs(RES + f'/mipmap-{d}', exist_ok=True)
        render(svg(px, 'squircle'), px, RES + f'/mipmap-{d}/ic_launcher.png')
        render(svg(px, 'circle'), px, RES + f'/mipmap-{d}/ic_launcher_round.png')
    os.makedirs(ROOT + '/out', exist_ok=True)
    render(svg(512, 'squircle'), 512, ROOT + '/out/shiying-icon-512.png')
    render(svg(512, 'full'), 512, ROOT + '/icon-src/adaptive-full-512.png')
    print('ok')
